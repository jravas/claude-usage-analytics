#!/usr/bin/env bash
# Build ui/dev/mock.local.js from your local usage index, for previewing the UI
# in a browser with real numbers (see CONTRIBUTING.md, "Previewing the UI").
#
# The output contains session titles and project paths. It is git-ignored;
# never commit it, and never ship it: delete it before `cargo tauri build`,
# because the app bundles everything under ui/.
#
# usage: scripts/make-mock.sh [--sessions N] [--copy-index] [--no-refresh]
#   --sessions N   capture `session <id>` for the top N sessions (default 10)
#   --copy-index   query a temporary copy of the index instead of the real one
#                  (implies --no-refresh); use it when another build of the app
#                  with a different schema shares the same index
#   --no-refresh   do not read new transcript lines first
#
# Env: USAGE_BIN=/path/to/usage uses a prebuilt CLI instead of `cargo run`.

set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/ui/dev/mock.local.js"
sessions=10
copy=0
refresh=1
while [ $# -gt 0 ]; do
  case "$1" in
    --sessions) sessions="$2"; shift 2 ;;
    --copy-index) copy=1; refresh=0; shift ;;
    --no-refresh) refresh=0; shift ;;
    -h|--help) sed -n '2,17p' "$0"; exit 0 ;;
    *) echo "make-mock: unknown argument $1" >&2; exit 1 ;;
  esac
done

if [ -z "${USAGE_BIN:-}" ]; then
  echo "building the usage CLI…" >&2
  (cd "$root" && cargo build --quiet --release -p usage-core --bin usage)
  target="$(cd "$root" && cargo metadata --format-version 1 --no-deps | sed -n 's/.*"target_directory":"\([^"]*\)".*/\1/p')"
  USAGE_BIN="${target:-$root/target}/release/usage"
fi

if [ "$copy" = 1 ]; then
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  data="Library/Application Support/digital.prototyp.claude-usage-analytics"
  mkdir -p "$tmp/$data"
  for f in index.sqlite index.sqlite-wal index.sqlite-shm; do
    [ -f "$HOME/$data/$f" ] && cp "$HOME/$data/$f" "$tmp/$data/$f"
  done
  export CLAUDE_CONFIG_DIR="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
  export HOME="$tmp"
fi

nr="--no-refresh"
usage() { "$USAGE_BIN" "$@" --json; }

if [ "$refresh" = 1 ]; then
  echo "reading new transcript lines…" >&2
  "$USAGE_BIN" models >/dev/null
fi

ranges="7 14 28 90"
dims="model project session effort agent hour weekday entrypoint"

{
  echo "// Generated by scripts/make-mock.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Contains private data: do not commit."
  echo "window.MOCK_DATA = {"
  echo "\"kind\": \"local\","
  echo "\"generated\": \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\","
  echo "\"responses\": {"
  printf '"models": ['
  "$USAGE_BIN" models $nr | sed 's/.*/"&"/' | paste -sd, -
  echo "],"
  printf '"overview": '; usage summary $nr; echo ","
  printf '"daily": '; usage daily --days 120 $nr; echo ","
  echo '"breakdown": {'
  first_r=1
  for r in $ranges; do
    [ $first_r = 1 ] || echo ","; first_r=0
    printf '"%s": {' "$r"
    first_d=1
    for d in $dims; do
      [ $first_d = 1 ] || echo ","; first_d=0
      limit=200; [ "$d" = session ] && limit=100
      printf '"%s": ' "$d"; usage by "$d" --days "$r" --limit "$limit" $nr
    done
    echo "}"
  done
  echo "},"
  echo '"sessions": {'
  first_s=1
  for id in $(usage by session --days 90 --limit "$sessions" $nr | sed -n 's/^    "key": "\(.*\)",$/\1/p'); do
    [ $first_s = 1 ] || echo ","; first_s=0
    echo "  session $id" >&2
    printf '"%s": ' "$id"; usage session "$id" $nr
  done
  echo "}"
  echo "},"
  echo '"extra": {'
  printf '"insights": '; usage insights --days 14 $nr; echo ","
  printf '"summary_preview": '; "$USAGE_BIN" export --preview --days 35 | python3 -c 'import json,sys; print(json.dumps(sys.stdin.read()))'
  echo "},"
  echo '"refresh": { "filesSeen": 1, "filesRead": 0, "newRequests": 0, "errors": 0, "ms": 1 }'
  echo "};"
} >"$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out ($(du -h "$out" | cut -f1 | tr -d ' ')). It is git-ignored; do not commit it." >&2
